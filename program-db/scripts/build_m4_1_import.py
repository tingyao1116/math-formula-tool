def write_outputs():
    IMPORT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    OUT_JSONL.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows), encoding="utf-8")


def upsert_db():
    payload = {"meta": {"count": 0}, "questions": []}
    if DB_PATH.exists():
        payload = json.loads(DB_PATH.read_text(encoding="utf-8-sig"))

    questions = payload.get("questions", [])
    new_ids = {r["id"] for r in rows}
    questions = [q for q in questions if q.get("id") not in new_ids]
    questions.extend(rows)
    payload["questions"] = questions
    payload.setdefault("meta", {})
    payload["meta"]["count"] = len(questions)
    DB_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


if __name__ == "__main__":
    write_outputs()
    upsert_db()
    print(f"records={len(rows)}")
    print(f"json={OUT_JSON}")
    print(f"jsonl={OUT_JSONL}")
    print(f"db={DB_PATH}")
