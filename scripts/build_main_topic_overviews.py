def normalize_topic_title(title: str) -> str:
    return TITLE_PREFIX_PATTERN.sub("", str(title or "")).strip()


def build_payload() -> dict:
    by_id = {}
    for spec in THEME_SPECS:
        title = normalize_topic_title(spec["title"])
        by_id[spec["topicId"]] = {
            "id": spec["topicId"],
            "title": title,
            "updatedAt": UPDATED_AT,
            "variants": [
                {
                    "id": "editable",
                    "label": "可修改版",
                    "sections": [
                        {
                            "type": "table",
                            "headers": ["重點", "整理"],
                            "rows": spec["editable_rows"],
                        }
                    ],
                },
                {
                    "id": "original",
                    "label": "原稿版",
                    "sections": [
                        {
                            "type": "pdf-page",
                            "src": f"exports/main-theme-overviews/{spec['pdf_file']}",
                            "note": title,
                        }
                    ],
                },
            ],
        }

    return {
        "meta": {
            "count": len(by_id),
            "updatedAt": UPDATED_AT,
            "source": "exports/main-theme-overviews/first-volume-topic-pdfs.json",
        },
        "byId": by_id,
    }


def main() -> None:
    payload = build_payload()
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    JS_PATH.parent.mkdir(parents=True, exist_ok=True)
    DB_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    JS_PATH.write_text(
        "window.mainTopicOverviewStore = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
